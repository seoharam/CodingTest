"""
0. 개념
- 백트래킹(BackTracking): 가능한 모든 후보를 하나씩 시도해보면서 해를 찾아가되, "이 방향은 답이 될 수 없다"는 게 확실해지는 순간 더 이상 진행하지 않고, 지금까지 선택했던 것을 원상복구(선택 취소)한 뒤 즉시 이전 상태로 되돌아가는 탐색 기법
  ㄴ 여기서 "되돌아간다"는 단순히 함수 호출이 끝나서 제어가 부모로 돌아오는 것(이건 DFS도 마찬가지)이 아니라, 방문 표시(chk)와 현재까지의 선택(rs) 같은 "상태"까지 원래대로 복구해서 같은 자원을 다른 분기에서 다시 쓸 수 있게 만든다는 뜻 -> 이게 있어야 DFS와 구분됨
  ㄴ (DFS.py의 chk와 차이) DFS의 방문 체크는 "이미 셌으니 그만 멈추자"(정답 1개, 끝내는 목적)인 반면, 백트래킹의 chk pruning은 "이 방향은 안 되니 멈추고 되돌아가서 다른 해를 찾자"(정답 여러 개, 다른 해 탐색이 목적) -> 같은 형태의 체크문이어도 목적이 다름
  ㄴ 보통 순열(=순서대로 나열)이 이에 해당됨 (조합과 다른점은 순서가 다르면 다른걸로 인정) / DFS와 다른점은 pruning을 중간에 해서 되돌리는 파트가 있음
  ㄴ 모든 경우의 수를 확인할 때 like 순열, But 반복문으로 확인 불가한 경우(=for문의 깊이(2중, 3중...)가 다를 때)
  ㄴ 여기서 시간 복잡도는 중복 가능일 경우 N^N, 불가능할 경우 N! (각각 N=8, 10)
  ㄴ (Tip) N이 작고, 재귀함수 사용 시 종료 시점 잊지 말기

1. 아이디어
- 백트래킹 재귀함수 안에서, for 돌면서 숫자 선택(이때 방문여부 확인)
- 재귀함수에서 M개를 선택할 경우 print

2. 시간복잡도
- N! = 8! > 가능

3. 자료구조
- 결과값 저장 int[]
- 방문여부 체크 bool[]
"""

import sys
input = sys.stdin.readline                                           # 시스템 도구 모음 -> 표준 입력 -> 한 줄을 읽는다 (입력속도 개선)

N, M = map(int, input().split())                                     # N: 전체 숫자 범위(1~N), M: 그중 몇 개를 뽑아 나열할지
rs = []                                                              # 지금 만들고 있는 하나의 순열(경로)을 담을 리스트
chk = [False] * (N+1)                                                # N+1 = 인덱스 관련 처리 (1~N을 그대로 인덱스로 쓰기 위해 0번 칸은 버림)

def recur(num):                                                      # num: 지금까지 몇 개를 뽑았는지 나타내는 깊이(depth)
    if num == M:                                                     # M개를 다 뽑았다면 하나의 순열이 완성된 것 (종료 조건, pruning 아님)
        print(''.join(map(str, rs)))                                 # rs에 쌓인 숫자들을 이어붙여 한 줄로 출력
        return                                                       # 더 뽑지 않고 재귀 종료 (더 깊이 들어가지 않음)
    for i in range(1, N+1):                                          # 1부터 N까지 순서대로 다음 숫자 후보를 확인
        if chk[i] == False:                                          # 아직 안 뽑은 숫자라면 (pruning: 이미 뽑은 숫자가 있는 분기는 건너뛰고, 다른 숫자로 또 다른 해를 찾으러 감)
            chk[i] = True                                            # 선택: 이 숫자를 뽑았다고 표시
            rs.append(i)                                             # 선택: 현재 순열(rs)의 끝에 추가
            recur(num+1)                                             # 재귀 호출: 한 개 더 뽑으러 깊이 들어감 (콜 스택에 쌓임 = LIFO)
            chk[i] = False                                           # 선택 취소: 되돌아왔으니 이 숫자를 다른 분기에서 다시 쓸 수 있게 복구
            rs.pop()                                                 # 선택 취소: rs에서도 마지막에 넣은 숫자를 제거

recur(0)                                                             # num=0(아직 아무것도 안 뽑음)부터 재귀 탐색 시작
