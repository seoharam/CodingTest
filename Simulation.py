"""
0. 개념
- 시뮬레이션(Simulation): 각 조건에 맞는 상황을 구현하는 문제
   ㄴ 지도상에서 이동하면서 탐험 / 배열 안에서 이동하면서 탐험 / 별도의 알고리즘은 없으나 구현력이 중요
   ㄴ 매 시험마다 1문제 이상 무조건 출제

* BFS/DFS와 달리 "어디까지 갈 수 있나"가 아니라 "규칙대로 정확히 굴렸을 때 어떻게 되나"를 묻는다
  ㄴ 그래서 방향 순서, 회전 방향, 종료 조건 같은 디테일 하나만 틀려도 답이 달라짐

1. 아이디어
- While문으로, 특정조건 종료될때까지 반복
- 4방향을 for문으로 탐색
- 더이상 탐색이 불가능할경우, 뒤로 한칸 후진
- 후진이 불가능하면 종료

2. 시간복잡도
- O(NM) : 50^2 = 2500 < 2억 -> 가능
  ㄴ 한 칸은 최대 한 번만 청소되므로(0 -> 2) 전체 반복 횟수가 칸 수에 비례

3. 자료구조
- map : int[][]                  # 0=청소 안 함, 1=벽, 2=청소 완료
- 로봇청소기 위치, 방향, 전체 청소한 곳 수

* 방향 인덱스 d : 0=북, 1=동, 2=남, 3=서 (문제에서 주는 규약)
  ㄴ 시계방향으로 배열했으므로 d+1 = 오른쪽 회전, d-1 = 왼쪽 회전
  ㄴ 이 문제는 "왼쪽부터 탐색"이라 d-1 방향으로 진행 => dy/dx 순서가 정답을 좌우함
"""

import sys
input = sys.stdin.readline                                         # 입력속도 개선

N, M = map(int, input().split())                                   # 세로 N, 가로 M 크기 입력
y,x,d = map(int, input().split())                                  # 행(row),열(column) 순서 / d는 처음 바라보는 방향
map = [list(map(int, input().split())) for _ in range(N)]          # N줄을 읽어 N x M 지도 생성 (이 줄부터 내장함수 map()은 가려짐)
cnt = 0                                                            # 청소한 칸의 총 개수

dy = [-1,0,1,0]                                                    # 북동남서 순서의 y(행) 변화량 / 북=행 감소, 남=행 증가
dx = [0,1,0,-1]                                                    # 북동남서 순서의 x(열) 변화량 / dy와 같은 인덱스끼리 짝지어 한 방향

while 1:                                                           # 종료 조건(후진 불가)을 만날 때까지 무한 반복
    if map[y][x] == 0:                                             # 1. 현재 위치가 아직 청소 안 된 칸이라면
        map[y][x] = 2                                              # 청소 완료로 표시 (다시 청소하지 않도록)
        cnt += 1                                                   # 청소한 칸 수 증가
    sw = False                                                     # 이번 턴에 전진했는지 여부 (False면 4방향 다 막힌 것)
    # 4방향 탐색
    for i in range(1,5):                                           # 왼쪽(d-1) -> 뒤(d-2) -> 오른쪽(d-3) -> 앞(d-4=d) 순서로 확인
        ny = y + dy[d-i]                                           # 바라보는 방향의 왼쪽으로 꺾어서 진행
        nx = x + dx[d-i]                                           # d-i가 음수여도 파이썬 음수 인덱싱이 -4~-1을 0~3으로 감아줌
        if 0<=ny<N and 0<=nx<M:                                    # 지도 범위를 벗어나지 않는지 확인
            if map[ny][nx] == 0:                                   # 아직 청소하지 않은 빈 칸이면 (1=벽, 2=이미 청소)
                # 그 방향으로 회전한 다음 한 칸을 전진하고 1번부터 진행
                d = (d-i+4)%4                                      # 회전: 음수를 0~3 범위로 정규화해 방향 갱신
                y = ny                                             # 전진한 위치로 이동
                x = nx
                sw = True                                          # 전진했음을 기록 -> 아래 후진 로직을 건너뜀
                break                                              # 더 볼 필요 없이 1번(청소)부터 다시 시작

    # 4방향 모두 있지 않은 경우
    if sw == False:                                                # 네 방향이 전부 벽이거나 이미 청소된 상태
        # 뒤쪽 방향이 막혀있는지 확인
        ny = y - dy[d]                                             # 방향은 그대로 두고 좌표만 뒤로 (전진의 반대 = 부호 반전)
        nx = x - dx[d]
        if 0 <= ny < N and 0 <= nx < M:                            # 뒤쪽이 지도 안인지 확인
            if map[ny][nx] == 1:                                   # 뒤쪽이 벽이면 후진 불가
                break                                              # 작동 정지
            else:
                y = ny                                             # 후진 (방향 d는 유지한 채 위치만 이동)
                x = nx
        else:
            break                                                  # 지도 밖이면 후진 불가 -> 정지

print(cnt)                                                         # 청소한 칸의 총 개수 출력
