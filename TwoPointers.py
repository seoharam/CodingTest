"""
0. 개념
- 투포인터(Two Pointers): 1차원배열이나 리스트에서 두 개의 점(위치/인덱스)을 기록하고 이동해가며 문제를 해결
   ㄴ 연속하다는 특성을 이용해서 처리 / 2개의 포인터(커서)가 움직이면서 계산   

1. 아이디어
- 투포인터를 활용
- for문으로, 처음에 K개값을 저장
- 다음인덱스 더해주고, 이전 인덱스 빼줌
- 이때마다 최대값을 갱신

2. 시간복잡도 (2억 = 1e+8)
- O(N) = 1e5 < 2억 가능 -> 각 횟수마다 뒤에꺼 빼고, 앞에꺼 더하는데 이는 상수 2라서 소거가능

3. 자료구조
- 각 숫자들 N개 저장 배열 : int[]
- K개의 값을 저장하는 변수 : int
- 최대값 : int

"""

import sys
input = sys.stdin.readline                                         # 공백/개행 처리 없이 그대로 불러와 입력속도 개선

N,K = map(int, input().split())                                    # 전체 숫자 개수 N, 연속으로 뽑을 개수 K
nums = list(map(int, input().split()))                             # N개의 숫자를 리스트로 입력받음
each = 0                                                           # 현재 윈도우(구간)의 합
# K개를 더해주기
for i in range(K):                                                 # 맨 처음 윈도우: 인덱스 0~K-1
    each += nums[i]                                                # 첫 K개를 미리 다 더해둠
maxv = each                                                        # 첫 윈도우 합을 최댓값의 시작점으로 설정

# 다음 인덱스 더해주고, 이전 인덱스 빼주기
for i in range(K, N):                                              # 윈도우를 한 칸씩 오른쪽으로 밀면서 진행
    each += nums[i]                                                # 새로 들어오는 값을 더하고
    each -= nums[i-K]                                              # 윈도우 밖으로 빠지는 값을 뺌 (매번 O(1))
    maxv = max(maxv, each)                                         # 갱신된 윈도우 합으로 최댓값 갱신

print(maxv)                                                        # K개 연속 구간의 최대 합 출력